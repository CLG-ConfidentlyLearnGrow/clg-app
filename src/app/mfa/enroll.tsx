// Summary: the steps to set up an authenticator app for two-step login.
//
"use client"; // Runs in the browser, so the steps can change as the person goes.

import { useState, useTransition } from "react"; // Lets the form remember the set-up and show a "starting" state.
import { startEnrollment, verifyTwoStep, type Enrollment } from "@/app/actions/mfa"; // The server actions to start set-up and check the code, and the set-up's type.
import { ActionForm } from "@/components/action-form"; // The form that sends to a server action and shows its reply.
import { Button, Field } from "@/components/ui"; // The button and labelled input box.

// Shows a "set up" button, then the QR code and code box.
export function EnrollTwoStep() {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null); // The set-up details (none until started).
  const [pending, startTransition] = useTransition(); // Whether it's starting, and the way to start it.

  if (!enrollment || "error" in enrollment) { // Not started yet, or it failed:
    return ( // shows:
      <div className="space-y-3">{/* a block with space between parts: */}
        {enrollment && "error" in enrollment && <p className="text-sm text-red-700">{enrollment.error}</p>}{/* any error in red, */}
        <p className="text-sm">{/* a line: */}
          You&apos;ll need an authenticator app on your phone, such as Microsoft Authenticator or Google Authenticator.{/* saying they need an authenticator app. */}
        </p>{/* End of the line. */}
        <Button disabled={pending} onClick={() => startTransition(async () => setEnrollment(await startEnrollment()))}>{/* A button that starts set-up (greyed out while starting): */}
          {pending ? "Starting…" : "Set up two-step login"}{/* its words change while starting. */}
        </Button>{/* End of the button. */}
      </div> // End of the block.
    ); // End of what's shown.
  } // End of that case.

  return ( // Started: shows:
    <div className="space-y-4">{/* a block with space between parts: */}
      <p className="text-sm">Scan this code with your authenticator app, then enter the 6-digit code it shows.</p>{/* how to scan and enter the code, */}
      {/* The QR code is an SVG data URL generated by Supabase. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="QR code for your authenticator app" className="h-48 w-48 bg-white p-2" />{/* the QR code picture, */}
      <p className="text-xs text-zinc-500">{/* a small grey line: */}
        Can&apos;t scan it? Enter this key instead: <code className="break-all">{enrollment.secret}</code>{/* with the key to type in if scanning doesn't work. */}
      </p>{/* End of the line. */}
      <ActionForm action={verifyTwoStep} submitLabel="Turn on two-step login">{/* A form that checks the code: */}
        <input type="hidden" name="factorId" value={enrollment.factorId} />{/* which app (hidden), */}
        <Field label="6-digit code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" required />{/* the code box (6 digits only). */}
      </ActionForm>{/* End of the form. */}
    </div> // End of the block.
  ); // End of what's shown.
} // End of EnrollTwoStep.
