"use client";

import { useState, useTransition } from "react";
import { startEnrollment, verifyTwoStep, type Enrollment } from "@/app/actions/mfa";
import { ActionForm } from "@/components/action-form";
import { Button, Field } from "@/components/ui";

export function EnrollTwoStep() {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [pending, startTransition] = useTransition();

  if (!enrollment || "error" in enrollment) {
    return (
      <div className="space-y-3">
        {enrollment && "error" in enrollment && <p className="text-sm text-red-700">{enrollment.error}</p>}
        <p className="text-sm">
          You&apos;ll need an authenticator app on your phone, such as Microsoft Authenticator or Google Authenticator.
        </p>
        <Button disabled={pending} onClick={() => startTransition(async () => setEnrollment(await startEnrollment()))}>
          {pending ? "Starting…" : "Set up two-step login"}
        </Button>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      <p className="text-sm">Scan this code with your authenticator app, then enter the 6-digit code it shows.</p>
      {/* The QR code is an SVG data URL generated by Supabase. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="QR code for your authenticator app" className="h-48 w-48 bg-white p-2" />
      <p className="text-xs text-zinc-500">
        Can&apos;t scan it? Enter this key instead: <code className="break-all">{enrollment.secret}</code>
      </p>
      <ActionForm action={verifyTwoStep} submitLabel="Turn on two-step login">
        <input type="hidden" name="factorId" value={enrollment.factorId} />
        <Field label="6-digit code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" required />
      </ActionForm>
    </div>
  );
}
